CREATE OR ALTER PROCEDURE [dbo].[sp_operationalNotices]
    @pjsonfile NVARCHAR(MAX)
AS
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @Outputmessage NVARCHAR(MAX) = '{"result":[{"value":"","msg":"","error":""}]}';

BEGIN TRY
    DECLARE @rowJson NVARCHAR(MAX);
    SELECT TOP 1 @rowJson = value FROM OPENJSON(@pjsonfile, '$.operationalNotices');

    DECLARE @action INT = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.action')),
            @id INT = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.operationalNoticeId')),
            @companyId INT = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.companyId')),
            @templateId INT = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.templateId')),
            @branchId INT = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.branchId')),
            @title NVARCHAR(120) = NULLIF(LTRIM(RTRIM(JSON_VALUE(@rowJson, '$.title'))), ''),
            @noticeType NVARCHAR(20) = NULLIF(JSON_VALUE(@rowJson, '$.noticeType'), ''),
            @customerMessage NVARCHAR(1000) = NULLIF(LTRIM(RTRIM(JSON_VALUE(@rowJson, '$.customerMessage'))), ''),
            @startDate DATE = TRY_CONVERT(DATE, JSON_VALUE(@rowJson, '$.startDate')),
            @endDate DATE = TRY_CONVERT(DATE, JSON_VALUE(@rowJson, '$.endDate')),
            @startTime TIME(0) = TRY_CONVERT(TIME(0), NULLIF(JSON_VALUE(@rowJson, '$.startTime'), '')),
            @endTime TIME(0) = TRY_CONVERT(TIME(0), NULLIF(JSON_VALUE(@rowJson, '$.endTime'), '')),
            @blocksReservations BIT = TRY_CONVERT(BIT, JSON_VALUE(@rowJson, '$.blocksReservations')),
            @updatedByUserId INT = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.updatedByUserId'));

    -- Sonora has no DST: US Mountain Standard Time = Hermosillo all year.
    DECLARE @today DATE = CAST(SYSUTCDATETIME() AT TIME ZONE 'UTC' AT TIME ZONE 'US Mountain Standard Time' AS DATE);

    IF @companyId IS NULL THROW 50000, 'companyId es obligatorio.', 1;

    IF @action IN (2, 3) AND NOT EXISTS (
        SELECT 1 FROM dbo.operationalNotices WHERE operationalNoticeId = @id AND companyId = @companyId)
        THROW 50001, 'Aviso no encontrado.', 1;

    IF @action = 3 -- FINALIZE early (e.g. the water came back). Never DELETE.
    BEGIN
        UPDATE dbo.operationalNotices
        SET status = 'finalizado', updatedByUserId = @updatedByUserId, updated_at = SYSUTCDATETIME()
        WHERE operationalNoticeId = @id AND companyId = @companyId;
        SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', 'Aviso finalizado');
    END
    ELSE IF @action IN (1, 2)
    BEGIN
        -- Merge with the stored row on update (only the keys sent change; "" clears the hours).
        IF @action = 2
            SELECT
                @templateId = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.templateId') = 1 THEN @templateId ELSE n.templateId END,
                @branchId = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.branchId') = 1 THEN @branchId ELSE n.branchId END,
                @title = COALESCE(@title, n.title),
                @noticeType = COALESCE(@noticeType, n.noticeType),
                @customerMessage = COALESCE(@customerMessage, n.customerMessage),
                @startDate = COALESCE(@startDate, n.startDate),
                @endDate = COALESCE(@endDate, n.endDate),
                @startTime = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.startTime') = 1 THEN @startTime ELSE n.startTime END,
                @endTime = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.endTime') = 1 THEN @endTime ELSE n.endTime END,
                @blocksReservations = COALESCE(@blocksReservations, n.blocksReservations)
            FROM dbo.operationalNotices n
            WHERE n.operationalNoticeId = @id AND n.companyId = @companyId;

        IF @title IS NULL OR @noticeType IS NULL OR @customerMessage IS NULL OR @startDate IS NULL OR @endDate IS NULL
            THROW 50002, 'Título, tipo, mensaje y fechas son obligatorios.', 1;
        IF @noticeType NOT IN ('cierre', 'horario_especial', 'aviso')
            THROW 50003, 'Tipo de aviso no válido.', 1;
        IF @endDate < @startDate
            THROW 50004, 'La fecha final no puede ser anterior a la inicial.', 1;
        IF @startTime IS NOT NULL AND @endTime IS NOT NULL AND @endTime <= @startTime
            THROW 50005, 'La hora final debe ser posterior a la inicial.', 1;
        IF @action = 1 AND @endDate < @today
            THROW 50006, 'No se puede publicar un aviso que ya terminó.', 1;
        IF @customerMessage LIKE '%{%}%'
            THROW 50007, 'El mensaje todavía tiene campos sin llenar entre llaves.', 1;
        IF @templateId IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM dbo.operationalNoticeTemplates WHERE operationalNoticeTemplateId = @templateId)
            THROW 50008, 'Plantilla no encontrada.', 1;
        IF @branchId IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM dbo.companiesBranch WHERE branchId = @branchId AND companyId = @companyId)
            THROW 50009, 'La sucursal no pertenece a esta empresa.', 1;

        IF @action = 1
        BEGIN
            INSERT INTO dbo.operationalNotices
                (companyId, templateId, branchId, title, noticeType, customerMessage, startDate, endDate,
                 startTime, endTime, blocksReservations, status, updatedByUserId)
            VALUES
                (@companyId, @templateId, @branchId, @title, @noticeType, @customerMessage, @startDate, @endDate,
                 @startTime, @endTime, ISNULL(@blocksReservations, CASE WHEN @noticeType = 'cierre' THEN 1 ELSE 0 END),
                 'activo', @updatedByUserId);
            SET @id = SCOPE_IDENTITY();
            SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', 'Aviso publicado');
        END
        ELSE
        BEGIN
            UPDATE dbo.operationalNotices SET
                templateId = @templateId, branchId = @branchId, title = @title, noticeType = @noticeType,
                customerMessage = @customerMessage, startDate = @startDate, endDate = @endDate,
                startTime = @startTime, endTime = @endTime, blocksReservations = @blocksReservations,
                updatedByUserId = @updatedByUserId, updated_at = SYSUTCDATETIME()
            WHERE operationalNoticeId = @id AND companyId = @companyId;
            SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', 'Aviso actualizado');
        END
    END
    ELSE
        THROW 50010, 'Acción no válida (1 publicar, 2 actualizar, 3 finalizar).', 1;

    SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].value', CAST(@id AS NVARCHAR(20)));
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].error', '1');
    SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', ERROR_MESSAGE());
END CATCH;

SELECT JSON_VALUE(value, '$.value') AS value,
       JSON_VALUE(value, '$.msg')   AS msg,
       JSON_VALUE(value, '$.error') AS error
FROM OPENJSON(@Outputmessage, '$.result');
GO

-- POS list. includePast = 1 adds notices that ended (or were finalized) in the last 90 days.
CREATE OR ALTER PROCEDURE [dbo].[sp_operationalNotices_all]
    @pjsonfile NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @companyId INT, @includePast BIT;
    SELECT TOP 1
        @companyId = TRY_CONVERT(INT, JSON_VALUE(value, '$.companyId')),
        @includePast = ISNULL(TRY_CONVERT(BIT, JSON_VALUE(value, '$.includePast')), 0)
    FROM OPENJSON(@pjsonfile, '$.operationalNotices');

    DECLARE @today DATE = CAST(SYSUTCDATETIME() AT TIME ZONE 'UTC' AT TIME ZONE 'US Mountain Standard Time' AS DATE);

    SELECT
        n.operationalNoticeId, n.companyId, n.templateId, n.branchId, n.title, n.noticeType, n.customerMessage,
        CONVERT(VARCHAR(10), n.startDate, 23) AS startDate,
        CONVERT(VARCHAR(10), n.endDate, 23)   AS endDate,
        ISNULL(CONVERT(VARCHAR(5), n.startTime, 108), '') AS startTime,
        ISNULL(CONVERT(VARCHAR(5), n.endTime, 108), '')   AS endTime,
        CAST(n.blocksReservations AS INT) AS blocksReservations,
        n.status, n.updatedByUserId,
        CONVERT(VARCHAR(30), n.created_At, 126) AS created_At,
        ISNULL(CONVERT(VARCHAR(30), n.updated_at, 126), '') AS updated_at,
        CASE
            WHEN n.status = 'finalizado' THEN 'finalizado'
            WHEN n.endDate < @today      THEN 'vencido'
            WHEN n.startDate > @today    THEN 'programado'
            ELSE 'vigente'
        END AS state
    FROM dbo.operationalNotices n
    WHERE n.companyId = @companyId
      AND ( (n.status = 'activo' AND n.endDate >= @today)
         OR (@includePast = 1 AND n.endDate >= DATEADD(DAY, -90, @today)) )
    ORDER BY n.startDate DESC, n.operationalNoticeId DESC
    FOR JSON PATH, INCLUDE_NULL_VALUES, ROOT('operationalNotices');
END;
GO

