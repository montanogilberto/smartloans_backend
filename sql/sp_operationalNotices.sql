-- What the agents read (X-Worker-Key): active notices that apply today or start within daysAhead.
-- No branchId = every notice of the company (company-wide and per-branch).
CREATE OR ALTER PROCEDURE [dbo].[sp_operationalNotices_active]
    @pjsonfile NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @companyId INT, @branchId INT, @daysAhead INT;
    SELECT TOP 1
        @companyId = TRY_CONVERT(INT, JSON_VALUE(value, '$.companyId')),
        @branchId = TRY_CONVERT(INT, JSON_VALUE(value, '$.branchId')),
        @daysAhead = ISNULL(TRY_CONVERT(INT, JSON_VALUE(value, '$.daysAhead')), 7)
    FROM OPENJSON(@pjsonfile, '$.operationalNotices');
    IF @daysAhead < 0 OR @daysAhead > 60 SET @daysAhead = 7;

    DECLARE @today DATE = CAST(SYSUTCDATETIME() AT TIME ZONE 'UTC' AT TIME ZONE 'US Mountain Standard Time' AS DATE);

    SELECT
        operationalNoticeId, branchId, title, noticeType, customerMessage,
        CONVERT(VARCHAR(10), startDate, 23) AS startDate,
        CONVERT(VARCHAR(10), endDate, 23)   AS endDate,
        ISNULL(CONVERT(VARCHAR(5), startTime, 108), '') AS startTime,
        ISNULL(CONVERT(VARCHAR(5), endTime, 108), '')   AS endTime,
        CAST(blocksReservations AS INT) AS blocksReservations,
        CASE WHEN @today BETWEEN startDate AND endDate THEN 1 ELSE 0 END AS appliesToday
    FROM dbo.operationalNotices
    WHERE companyId = @companyId
      AND status = 'activo'
      AND endDate >= @today
      AND startDate <= DATEADD(DAY, @daysAhead, @today)
      AND (@branchId IS NULL OR branchId IS NULL OR branchId = @branchId)
    ORDER BY startDate, operationalNoticeId
    FOR JSON PATH, INCLUDE_NULL_VALUES, ROOT('operationalNotices');
END;
GO

