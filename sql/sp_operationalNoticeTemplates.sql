CREATE OR ALTER PROCEDURE [dbo].[sp_operationalNoticeTemplates]
    @pjsonfile NVARCHAR(MAX)
AS
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @Outputmessage NVARCHAR(MAX) = '{"result":[{"value":"","msg":"","error":""}]}';

BEGIN TRY
    DECLARE @action INT, @id INT, @templateKey NVARCHAR(50), @name NVARCHAR(80), @description NVARCHAR(200),
            @icon NVARCHAR(50), @noticeType NVARCHAR(20), @defaultTitle NVARCHAR(120),
            @defaultMessage NVARCHAR(1000), @variables NVARCHAR(200), @blocksReservations BIT,
            @sortOrder INT, @rowJson NVARCHAR(MAX);

    SELECT TOP 1 @rowJson = value FROM OPENJSON(@pjsonfile, '$.operationalNoticeTemplates');

    SELECT @action = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.action')),
           @id = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.operationalNoticeTemplateId')),
           @templateKey = LTRIM(RTRIM(JSON_VALUE(@rowJson, '$.templateKey'))),
           @name = NULLIF(LTRIM(RTRIM(JSON_VALUE(@rowJson, '$.name'))), ''),
           @description = JSON_VALUE(@rowJson, '$.description'),
           @icon = JSON_VALUE(@rowJson, '$.icon'),
           @noticeType = NULLIF(JSON_VALUE(@rowJson, '$.noticeType'), ''),
           @defaultTitle = NULLIF(LTRIM(RTRIM(JSON_VALUE(@rowJson, '$.defaultTitle'))), ''),
           @defaultMessage = NULLIF(LTRIM(RTRIM(JSON_VALUE(@rowJson, '$.defaultMessage'))), ''),
           @variables = JSON_VALUE(@rowJson, '$.variables'),
           @blocksReservations = TRY_CONVERT(BIT, JSON_VALUE(@rowJson, '$.blocksReservations')),
           @sortOrder = TRY_CONVERT(INT, JSON_VALUE(@rowJson, '$.sortOrder'));

    IF @action = 1 -- INSERT
    BEGIN
        IF @templateKey IS NULL OR @templateKey = '' OR @name IS NULL OR @noticeType IS NULL
           OR @defaultTitle IS NULL OR @defaultMessage IS NULL
            THROW 50001, 'templateKey, name, noticeType, defaultTitle y defaultMessage son obligatorios.', 1;
        IF EXISTS (SELECT 1 FROM dbo.operationalNoticeTemplates WHERE templateKey = @templateKey)
            THROW 50002, 'Ya existe una plantilla con esa clave.', 1;

        INSERT INTO dbo.operationalNoticeTemplates
            (templateKey, name, description, icon, noticeType, defaultTitle, defaultMessage, variables,
             blocksReservations, sortOrder, status)
        VALUES (@templateKey, @name, NULLIF(@description, ''), NULLIF(@icon, ''), @noticeType, @defaultTitle,
                @defaultMessage, NULLIF(@variables, ''), ISNULL(@blocksReservations, 0), @sortOrder, 'activo');
        SET @id = SCOPE_IDENTITY();
        SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', 'Plantilla creada');
    END
    ELSE IF @action = 2 -- UPDATE: only the keys sent; templateKey never changes
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM dbo.operationalNoticeTemplates WHERE operationalNoticeTemplateId = @id)
            THROW 50003, 'Plantilla no encontrada.', 1;

        UPDATE dbo.operationalNoticeTemplates SET
            name               = COALESCE(@name, name),
            description        = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.description') = 1 THEN NULLIF(@description, '') ELSE description END,
            icon               = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.icon') = 1 THEN NULLIF(@icon, '') ELSE icon END,
            noticeType         = COALESCE(@noticeType, noticeType),
            defaultTitle       = COALESCE(@defaultTitle, defaultTitle),
            defaultMessage     = COALESCE(@defaultMessage, defaultMessage),
            variables          = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.variables') = 1 THEN NULLIF(@variables, '') ELSE variables END,
            blocksReservations = COALESCE(@blocksReservations, blocksReservations),
            sortOrder          = CASE WHEN JSON_PATH_EXISTS(@rowJson, '$.sortOrder') = 1 THEN @sortOrder ELSE sortOrder END,
            status             = 'activo',
            updated_at         = SYSUTCDATETIME()
        WHERE operationalNoticeTemplateId = @id;
        SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', 'Plantilla actualizada');
    END
    ELSE IF @action = 3 -- RETIRE (never DELETE: published notices keep their templateId)
    BEGIN
        UPDATE dbo.operationalNoticeTemplates SET status = 'retirado', updated_at = SYSUTCDATETIME()
        WHERE operationalNoticeTemplateId = @id;
        IF @@ROWCOUNT = 0 THROW 50003, 'Plantilla no encontrada.', 1;
        SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', 'Plantilla retirada');
    END
    ELSE
        THROW 50000, 'Acción no válida (1 crear, 2 actualizar, 3 retirar).', 1;

    SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].value', CAST(@id AS NVARCHAR(20)));
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].error', '1');
    SET @Outputmessage = JSON_MODIFY(@Outputmessage, '$.result[0].msg', ERROR_MESSAGE());
END CATCH;

SELECT JSON_VALUE(value, '$.value') AS value,
       JSON_VALUE(value, '$.msg')   AS msg,
       JSON_VALUE(value, '$.error') AS error
FROM OPENJSON(@Outputmessage, '$.result');
GO

CREATE OR ALTER PROCEDURE [dbo].[sp_operationalNoticeTemplates_all]
    @pjsonfile NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;
    -- Default 'activo' (the library); send "status": "all" to include retired ones (platform admin).
    DECLARE @status NVARCHAR(20) = ISNULL(
        (SELECT TOP 1 JSON_VALUE(value, '$.status') FROM OPENJSON(@pjsonfile, '$.operationalNoticeTemplates')),
        'activo');

    SELECT
        operationalNoticeTemplateId,
        templateKey,
        name,
        ISNULL(description, '')    AS description,
        ISNULL(icon, '')           AS icon,
        noticeType,
        defaultTitle,
        defaultMessage,
        ISNULL(variables, '')      AS variables,
        CAST(blocksReservations AS INT) AS blocksReservations,
        sortOrder,
        status,
        CONVERT(VARCHAR(30), created_At, 126) AS created_At,
        ISNULL(CONVERT(VARCHAR(30), updated_at, 126), '') AS updated_at
    FROM dbo.operationalNoticeTemplates
    WHERE @status = 'all' OR status = @status
    ORDER BY CASE WHEN sortOrder IS NULL THEN 1 ELSE 0 END, sortOrder, name
    FOR JSON PATH, INCLUDE_NULL_VALUES, ROOT('operationalNoticeTemplates');
END;
GO

CREATE OR ALTER PROCEDURE [dbo].[sp_operationalNoticeTemplates_one]
    @pjsonfile NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @id INT = TRY_CONVERT(INT,
        (SELECT TOP 1 JSON_VALUE(value, '$.operationalNoticeTemplateId')
         FROM OPENJSON(@pjsonfile, '$.operationalNoticeTemplates')));

    SELECT
        operationalNoticeTemplateId, templateKey, name,
        ISNULL(description, '') AS description, ISNULL(icon, '') AS icon, noticeType,
        defaultTitle, defaultMessage, ISNULL(variables, '') AS variables,
        CAST(blocksReservations AS INT) AS blocksReservations, sortOrder, status
    FROM dbo.operationalNoticeTemplates
    WHERE operationalNoticeTemplateId = @id
    FOR JSON PATH, INCLUDE_NULL_VALUES, ROOT('operationalNoticeTemplates');
END;
GO
