"""
Operational notices of one company (dbo.operationalNotices): temporary situations
(closed today for lack of water, special hours, a service down) that the agents must
tell customers, with priority over the regular schedule. Lifecycle: publish (1),
update / extend (2), finalize early (3); never deleted. The route stamps companyId
rows that the session may act on and updatedByUserId from the token.

Generated by posgmo-factory (PRD tests/prd_operationalNotice.json, 2026-11-18) and
fixed by hand: the write SP answers one row (value, msg, error), not JSON; who
published / changed / finalized each notice is kept with log_audit per field
(no separate history table).
"""
import json

from fastapi.responses import JSONResponse

from databases import connection
from observability import log_audit

_KEY = "operationalNotices"
_AUDITED = ("title", "noticeType", "customerMessage", "startDate", "endDate", "startTime", "endTime",
            "blocksReservations", "branchId", "templateId", "status")


def _read_json(procedure: str, json_file: dict) -> dict:
    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute(f"EXEC [dbo].[{procedure}] @pjsonfile = %s", (json.dumps(json_file),))
        raw = "".join(r[0] for r in cursor.fetchall() if r and r[0])
        return json.loads(raw) if raw else {_KEY: []}
    finally:
        if conn:
            conn.close()


def _one(company_id, notice_id) -> dict:
    if not company_id or not notice_id:
        return {}
    try:
        rows = _read_json("sp_operationalNotices_one",
                          {_KEY: [{"companyId": company_id, "operationalNoticeId": notice_id}]}).get(_KEY) or []
        return rows[0] if rows else {}
    except Exception:
        return {}


def operationalNotices_sp(json_file: dict):
    """{"operationalNotices": [{action 1|2|3, companyId, operationalNoticeId?, title?, ...,
    updatedByUserId}]}"""
    rows = json_file.get(_KEY)
    if not isinstance(rows, list) or len(rows) != 1 or not isinstance(rows[0], dict):
        return JSONResponse(content={"error": f"{_KEY} must hold exactly one row"}, status_code=400)
    row = rows[0]
    action = int(row.get("action") or 0)
    company_id = row.get("companyId")
    before = _one(company_id, row.get("operationalNoticeId")) if action in (2, 3) else {}

    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute("EXEC [dbo].[sp_operationalNotices] @pjsonfile = %s", (json.dumps({_KEY: [row]}),))
        result = cursor.fetchone()
        value, msg, error = (list(result) + [None, None, None])[:3] if result else ("", "", "1")
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
    finally:
        if conn:
            conn.close()

    if error:
        return JSONResponse(content={"status": "error", "message": msg or "Error"}, status_code=400)

    notice_id = int(value) if str(value or "").isdigit() else None
    after = _one(company_id, notice_id)
    audit_action = {1: "INSERT", 2: "UPDATE", 3: "FINALIZE"}.get(action, "UPDATE")
    for field in _AUDITED:
        old, new = before.get(field), after.get(field)
        if (old if old is not None else "") != (new if new is not None else ""):
            log_audit("operationalNotices", notice_id, field, old, new, action=audit_action)
    return JSONResponse(content={"status": "success", "message": msg or "", "value": notice_id or ""},
                        status_code=200)


def all_operationalNotices_sp(json_file: dict):
    try:
        return JSONResponse(content=_read_json("sp_operationalNotices_all", json_file), status_code=200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)


def active_operationalNotices_sp(json_file: dict):
    try:
        return JSONResponse(content=_read_json("sp_operationalNotices_active", json_file), status_code=200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
