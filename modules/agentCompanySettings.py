"""
Per-company settings of a catalog agent (dbo.agentCompanySettings): how the agent
introduces itself (displayName) and the business's behavior notes
(extraInstructions). Business DATA (prices, hours, address, promotions) is not
here: the agent reads it from businessInfo / promotions.

Generated by posgmo-factory (PRD tests/prd_agentCompanySetting.json, 2026-11-18)
and fixed by hand: sp_agentCompanySettings answers one row (value, msg, error),
not JSON — the generated json.loads(row[0]) turned every SP error into "ok";
log_audit added.
"""
import json

from fastapi.responses import JSONResponse

from databases import connection
from observability import log_audit

_KEY = "agentCompanySettings"


def _read_json(procedure: str, json_file: dict) -> dict:
    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute(f"EXEC [dbo].[{procedure}] @pjsonfile = %s", (json.dumps(json_file),))
        raw = "".join(r[0] for r in cursor.fetchall() if r and r[0])
        return json.loads(raw) if raw else {_KEY: []}
    finally:
        if conn:
            conn.close()


def _one(company_id, agent_id) -> dict:
    try:
        rows = _read_json("sp_agentCompanySettings_one",
                          {_KEY: [{"companyId": company_id, "agentId": agent_id}]}).get(_KEY) or []
        return rows[0] if rows else {}
    except Exception:
        return {}


def agentCompanySettings_sp(json_file: dict):
    """Upsert one row: {"agentCompanySettings": [{companyId, agentId, displayName?,
    extraInstructions?, updatedByUserId}]} (action is always 1: upsert)."""
    rows = json_file.get(_KEY)
    if not isinstance(rows, list) or len(rows) != 1 or not isinstance(rows[0], dict):
        return JSONResponse(content={"error": f"{_KEY} must hold exactly one row"}, status_code=400)
    row = {**rows[0], "action": 1}
    company_id, agent_id = row.get("companyId"), row.get("agentId")
    before = _one(company_id, agent_id)

    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute("EXEC [dbo].[sp_agentCompanySettings] @pjsonfile = %s", (json.dumps({_KEY: [row]}),))
        result = cursor.fetchone()
        _value, msg, error = (list(result) + [None, None, None])[:3] if result else ("", "", "1")
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
    finally:
        if conn:
            conn.close()

    if error:
        return JSONResponse(content={"status": "error", "message": msg or "Error"}, status_code=400)

    after = _one(company_id, agent_id)
    setting_id = int(after.get("agentCompanySettingId") or 0) or None
    for field in ("displayName", "extraInstructions"):
        if (before.get(field) or "") != (after.get(field) or ""):
            log_audit("agentCompanySettings", setting_id, field, before.get(field) or None,
                      after.get(field) or None, action="UPDATE" if before else "INSERT")
    return JSONResponse(content={"status": "success", "message": msg or "", "value": setting_id or ""},
                        status_code=200)


def all_agentCompanySettings_sp(json_file: dict):
    try:
        return JSONResponse(content=_read_json("sp_agentCompanySettings_all", json_file), status_code=200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)


def one_agentCompanySettings_sp(json_file: dict):
    try:
        return JSONResponse(content=_read_json("sp_agentCompanySettings_one", json_file), status_code=200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
