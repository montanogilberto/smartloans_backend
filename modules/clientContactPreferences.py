"""Marketing consent per client and channel (sp_clientContactPreferences).

Generated by posgmo-factory (tests/prd_clientContactPreference.json), corrected
by hand: the SPs upsert on (companyId, clientId, channel), and the WhatsApp
BAJA/ALTA keyword resolves the client from the sender's phone inside the SP
(action 4) instead of trusting a clientId in a request body. The keyword is
NOT an HTTP route: anyone could opt a phone in or out through it. Only the
inbound webhook (modules/whatsappCloud.py), where Meta authenticates the
sender, calls handle_keyword().

Scope is marketing only: receipts and operational notices never read this.
"""
import json
import logging
import re
import unicodedata

from fastapi.responses import JSONResponse

from databases import connection
from observability import log_audit, log_workflow_step

logger = logging.getLogger(__name__)

OPT_OUT_KEYWORDS = {"BAJA", "STOP", "ALTO", "CANCELAR"}
OPT_IN_KEYWORDS = {"ALTA"}

OPT_OUT_REPLY = ("Listo, ya no te enviaremos promociones por WhatsApp. "
                 "Responde ALTA si quieres volver a recibirlas.")
OPT_IN_REPLY = ("Listo, volverás a recibir nuestras promociones por WhatsApp. "
                "Responde BAJA para dejar de recibirlas.")
OPT_IN_NOT_FOUND_REPLY = ("No encontramos un cliente registrado con este número. "
                          "Pide en sucursal que te registren para recibir promociones.")
FAILED_REPLY = "No pudimos procesar tu solicitud. Intenta de nuevo en unos minutos."


def _exec(sp_name: str, json_file: dict):
    """One JSON document from the SP (FOR JSON may split it across rows), or None."""
    conn = connection()
    try:
        cursor = conn.cursor()
        cursor.execute(f"EXEC [dbo].[{sp_name}] @pjsonfile = %s", (json.dumps(json_file),))
        text = "".join(r[0] for r in cursor.fetchall() if r and r[0])
        return json.loads(text) if text else None
    finally:
        conn.close()


def clientContactPreferences_sp(json_file: dict):
    """action 1|2 upsert on (companyId, clientId, channel), 3 delete."""
    try:
        result = _exec("sp_clientContactPreferences", json_file) or {"result": []}
        row = (result.get("result") or [{}])[0]
        payload = (json_file.get("clientContactPreferences") or [{}])[0]
        if not row.get("error"):
            log_audit("clientContactPreference", payload.get("clientId"), payload.get("channel"),
                      None, payload.get("marketingOptIn"),
                      action="DELETE" if payload.get("action") == 3 else "UPSERT")
        return JSONResponse(content=result, status_code=400 if row.get("error") else 200)
    except Exception as e:
        logger.exception("[clientContactPreferences] upsert failed")
        return JSONResponse(content={"error": str(e)}, status_code=500)


def all_clientContactPreferences_sp(json_file: dict):
    """All preferences of the company; optional clientId narrows to one client."""
    try:
        result = _exec("sp_clientContactPreferences_all", json_file)
        return JSONResponse(content=result or {"clientContactPreferences": []}, status_code=200)
    except Exception as e:
        logger.exception("[clientContactPreferences] list failed")
        return JSONResponse(content={"error": str(e)}, status_code=500)


def one_clientContactPreferences_sp(json_file: dict):
    """One row by clientContactPreferenceId, only inside the given companyId."""
    try:
        result = _exec("sp_clientContactPreferences_one", json_file)
        return JSONResponse(content=result or {"clientContactPreferences": []}, status_code=200)
    except Exception as e:
        logger.exception("[clientContactPreferences] get one failed")
        return JSONResponse(content={"error": str(e)}, status_code=500)


def _keyword(text: str | None) -> str:
    """'  baja. ' → 'BAJA'; accents dropped so 'Cancelár' still counts. Only a
    message that is JUST the keyword counts: 'no me den de baja' is a sentence."""
    plain = unicodedata.normalize("NFKD", text or "").encode("ascii", "ignore").decode()
    return re.sub(r"[^A-Za-z]", "", plain).upper()


def handle_keyword(company_id: int, phone: str, text: str | None) -> str | None:
    """WhatsApp BAJA/STOP/ALTO/CANCELAR or ALTA → the confirmation to send back,
    or None when the message is not a keyword (the bot handles it as usual).
    Never logs the phone."""
    word = _keyword(text)
    if word in OPT_OUT_KEYWORDS:
        opt_in = 0
    elif word in OPT_IN_KEYWORDS:
        opt_in = 1
    else:
        return None
    try:
        result = _exec("sp_clientContactPreferences", {"clientContactPreferences": [{
            "action": 4, "companyId": company_id, "phone": phone, "marketingOptIn": opt_in}]}) or {}
        row = (result.get("result") or [{}])[0]
        if row.get("error"):
            raise RuntimeError(row.get("msg"))
        updated = int(row.get("value") or 0)
    except Exception:
        logger.exception("[clientContactPreferences] keyword failed | company=%s optIn=%s", company_id, opt_in)
        return FAILED_REPLY
    log_workflow_step("whatsapp_marketing_keyword", action="opt_in" if opt_in else "opt_out",
                      workflow_name="marketing_consent", entity="clientContactPreference",
                      response={"companyId": company_id, "clientsUpdated": updated})
    logger.info("[clientContactPreferences] keyword | company=%s optIn=%s clientsUpdated=%s",
                company_id, opt_in, updated)
    if opt_in and updated == 0:
        return OPT_IN_NOT_FOUND_REPLY
    # An opt-out from an unknown number still gets the confirmation: no client
    # behind it means no campaign can reach it anyway.
    return OPT_IN_REPLY if opt_in else OPT_OUT_REPLY
