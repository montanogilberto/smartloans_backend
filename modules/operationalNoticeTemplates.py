"""
Platform library of operational notice templates (dbo.operationalNoticeTemplates).
No companyId: one list for the whole platform, edited only by a SmartLoans admin.

Generated by posgmo-factory (PRD tests/prd_operationalNoticeTemplate.json, 2026-11-18)
and fixed by hand: the write SP answers one row (value, msg, error), not JSON;
log_audit per changed field.
"""
import json

from fastapi.responses import JSONResponse

from databases import connection
from observability import log_audit

_KEY = "operationalNoticeTemplates"
_AUDITED = ("name", "description", "icon", "noticeType", "defaultTitle", "defaultMessage",
            "variables", "blocksReservations", "sortOrder", "status")


def _read_json(procedure: str, json_file: dict) -> dict:
    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute(f"EXEC [dbo].[{procedure}] @pjsonfile = %s", (json.dumps(json_file),))
        raw = "".join(r[0] for r in cursor.fetchall() if r and r[0])
        return json.loads(raw) if raw else {_KEY: []}
    finally:
        if conn:
            conn.close()


def _one(template_id) -> dict:
    if not template_id:
        return {}
    try:
        rows = _read_json("sp_operationalNoticeTemplates_one",
                          {_KEY: [{"operationalNoticeTemplateId": template_id}]}).get(_KEY) or []
        return rows[0] if rows else {}
    except Exception:
        return {}


def operationalNoticeTemplates_sp(json_file: dict):
    """{"operationalNoticeTemplates": [{action 1|2|3, operationalNoticeTemplateId?, templateKey?, ...}]}"""
    rows = json_file.get(_KEY)
    if not isinstance(rows, list) or len(rows) != 1 or not isinstance(rows[0], dict):
        return JSONResponse(content={"error": f"{_KEY} must hold exactly one row"}, status_code=400)
    row = rows[0]
    action = int(row.get("action") or 0)
    before = _one(row.get("operationalNoticeTemplateId")) if action in (2, 3) else {}

    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute("EXEC [dbo].[sp_operationalNoticeTemplates] @pjsonfile = %s", (json.dumps({_KEY: [row]}),))
        result = cursor.fetchone()
        value, msg, error = (list(result) + [None, None, None])[:3] if result else ("", "", "1")
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
    finally:
        if conn:
            conn.close()

    if error:
        return JSONResponse(content={"status": "error", "message": msg or "Error"}, status_code=400)

    template_id = int(value) if str(value or "").isdigit() else None
    after = _one(template_id)
    audit_action = {1: "INSERT", 2: "UPDATE", 3: "RETIRE"}.get(action, "UPDATE")
    for field in _AUDITED:
        old, new = before.get(field), after.get(field)
        if (old if old is not None else "") != (new if new is not None else ""):
            log_audit("operationalNoticeTemplates", template_id, field, old, new, action=audit_action)
    return JSONResponse(content={"status": "success", "message": msg or "", "value": template_id or ""},
                        status_code=200)


def all_operationalNoticeTemplates_sp(json_file: dict):
    try:
        return JSONResponse(content=_read_json("sp_operationalNoticeTemplates_all", json_file), status_code=200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
