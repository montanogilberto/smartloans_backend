"""
Client Acquisition — location validation: demand signals (who wants which
service concept, and in which zone).

Generated by posgmo-factory (PRD tests/prd_demandSignal.json, 2026-11-10) and
fixed by hand. Rows are written ONLY from the WhatsApp agent path
(modules/whatsappReservations, RECORD_DEMAND_SIGNAL) through
record_demand_signal(); there is no public create/delete route, because a public
write would let anyone forge demand in a zone.
"""

import json

from fastapi.responses import JSONResponse

from databases import connection
from observability.logger import workflow_step


def record_demand_signal(json_file: dict) -> dict:
    """Upsert one signal. json_file is the SP's @pjsonfile shape:
    {"demandSignals": [{companyId, channelId, customerPhone, concept, ...}]}.
    companyId, channelId and customerPhone must come from the WhatsApp channel
    and sender, never from the agent. Returns {"demandSignalId", "intentLevel"}.
    Raises on failure; workflow_step logs it."""
    with workflow_step("record_demand_signal", workflow_name="client_acquisition",
                       entity="demandSignal", action="upsert"):
        conn = None
        try:
            conn = connection()
            cursor = conn.cursor()
            cursor.execute("EXEC [dbo].[sp_demandSignals] @pjsonfile = %s", (json.dumps(json_file),))
            rows = cursor.fetchall()
            result = json.loads("".join(r[0] for r in rows if r and r[0]) or "{}")
            if result.get("error"):
                raise RuntimeError(f"sp_demandSignals: {result['error']}")
            return result["result"][0]
        finally:
            if conn:
                conn.close()


def _read_sp(procedure: str, json_file: dict) -> JSONResponse:
    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute(f"EXEC [dbo].[{procedure}] @pjsonfile = %s", (json.dumps(json_file),))
        rows = cursor.fetchall()
        # SQL Server may split long JSON across rows: always join.
        raw = "".join(r[0] for r in rows if r and r[0])
        content = json.loads(raw) if raw else {"error": "empty response"}
        return JSONResponse(content=content, status_code=400 if "error" in content else 200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
    finally:
        if conn:
            conn.close()


def all_demandSignals_sp(json_file: dict) -> JSONResponse:
    return _read_sp("sp_demandSignals_all", json_file)


def one_demandSignals_sp(json_file: dict) -> JSONResponse:
    return _read_sp("sp_demandSignals_one", json_file)


def zone_summary_demandSignals_sp(json_file: dict) -> JSONResponse:
    return _read_sp("sp_demandSignals_zoneSummary", json_file)
