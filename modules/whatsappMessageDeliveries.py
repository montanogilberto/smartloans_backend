"""whatsappMessageDeliveries — Meta delivery receipts of outbound WhatsApp messages
(one row per wamid), written in-process by modules/whatsappCloud.py:
  - send side: right after Meta accepts a send (status 'accepted', links the
    dbo.whatsappMessages row the POS thread renders);
  - webhook side: every value.statuses[] receipt (sent / delivered / read / failed).
The SP keeps the status monotonic and fills the link in whatever order they arrive.
Read by sp_whatsappAgentConversations 'thread' (bubble ticks); no HTTP route.

Generated by posgmo-factory (tests/prd_whatsappMessageDelivery.json, 2026-11-12) and
reduced to the one write path; see sql/sp_whatsappMessageDeliveries.sql for the fixes.
"""
import json
import logging

from databases import connection
from observability import log_workflow_step

logger = logging.getLogger(__name__)

STATUSES = ("accepted", "sent", "delivered", "read", "failed")


def upsert_delivery(json_file: dict) -> int | None:
    """Upserts one receipt by providerMessageId (wamid).

    json_file: { companyId, channelId, providerMessageId, status,
                 whatsappMessageId?, senderKind?, statusTimestamp? (unix s), errorCode?, errorTitle? }
    Returns whatsappMessageDeliveryId, or None on any error — never raises: a
    receipt must not break a send or the webhook. Never logs the phone or text."""
    if not json_file.get("providerMessageId") or json_file.get("status") not in STATUSES:
        return None
    row_in = {**json_file, "action": 1}
    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute("EXEC [dbo].[sp_whatsappMessageDeliveries] @pjsonfile = %s",
                       (json.dumps({"whatsappMessageDeliveries": [row_in]}),))
        row = cursor.fetchone()
        conn.commit()
        if not row or (len(row) > 2 and row[2] == "1"):
            logger.warning("[whatsappMessageDeliveries] upsert refused | id=%s status=%s msg=%s",
                           json_file.get("providerMessageId"), json_file.get("status"),
                           row[1] if row and len(row) > 1 else None)
            return None
        if json_file.get("status") == "failed":
            # Code + title only: no phone, no text.
            log_workflow_step("delivery_status", workflow_name="whatsapp_chat", status="FAILED",
                              entity="whatsappChannel", entity_id=json_file.get("channelId"),
                              message=f"code={json_file.get('errorCode')} {json_file.get('errorTitle') or ''}"[:200])
        try:
            return int(row[0]) if row[0] not in (None, "") else None
        except (TypeError, ValueError):
            return None
    except Exception:
        logger.exception("[whatsappMessageDeliveries] upsert failed | id=%s", json_file.get("providerMessageId"))
        return None
    finally:
        if conn:
            conn.close()
