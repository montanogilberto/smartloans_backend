"""
Platform catalog of the LoanAgents_SmartLoans agents (dbo.agents): one list for
every company, no companyId. A row describes an agent; its prompt, model and
tools stay in code in LoanAgents_SmartLoans.

Generated by posgmo-factory (PRD tests/prd_agent.json, 2026-11-18) and fixed by
hand: sp_agents answers one row (value, msg, error), not a JSON column, so the
generated json.loads(row[0]) made every save a 500; audit ids are ints.
"""
import json

from fastapi.responses import JSONResponse

from databases import connection
from observability import log_audit

_AUDIT_ACTIONS = {1: "INSERT", 2: "UPDATE", 3: "RETIRE"}
_AUDIT_FIELDS = ("name", "description", "area", "endpoint", "model", "customerFacing", "status")


def _read_json(procedure: str, json_file: dict) -> dict:
    """FOR JSON output of a read SP; SQL Server may split it across rows."""
    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute(f"EXEC [dbo].[{procedure}] @pjsonfile = %s", (json.dumps(json_file),))
        raw = "".join(r[0] for r in cursor.fetchall() if r and r[0])
        return json.loads(raw) if raw else {"agents": []}
    finally:
        if conn:
            conn.close()


def _one(identifier: dict) -> dict:
    """The agent's row as a dict, {} when missing (audit before/after images)."""
    try:
        rows = _read_json("sp_agents_one", {"agents": [identifier]}).get("agents") or []
        return rows[0] if rows else {}
    except Exception:
        return {}


def agents_sp(json_file: dict):
    rows = json_file.get("agents")
    if not isinstance(rows, list) or not rows or not isinstance(rows[0], dict):
        return JSONResponse(content={"error": "agents array missing or empty"}, status_code=400)
    payload = rows[0]
    action = int(payload.get("action") or 0)
    if action not in _AUDIT_ACTIONS:
        return JSONResponse(content={"error": "action must be 1, 2 or 3"}, status_code=400)
    identifier = {"agentId": payload["agentId"]} if payload.get("agentId") else {"agentKey": payload.get("agentKey")}
    before = _one(identifier) if action in (2, 3) else {}

    conn = None
    try:
        conn = connection()
        cursor = conn.cursor()
        cursor.execute("EXEC [dbo].[sp_agents] @pjsonfile = %s", (json.dumps(json_file),))
        row = cursor.fetchone()
        value, msg, error = (list(row) + [None, None, None])[:3] if row else ("", "", "1")
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
    finally:
        if conn:
            conn.close()

    if error:
        return JSONResponse(content={"status": "error", "message": msg or "Error"}, status_code=400)

    after = _one(identifier if action != 1 else {"agentKey": payload.get("agentKey")})
    agent_id = int(after.get("agentId") or before.get("agentId") or 0) or None
    if action == 1:
        log_audit("agents", agent_id, "status", None, after.get("status"), action="INSERT")
    else:
        for field in _AUDIT_FIELDS:
            if before.get(field) != after.get(field):
                log_audit("agents", agent_id, field, before.get(field), after.get(field),
                          action=_AUDIT_ACTIONS[action])
    return JSONResponse(content={"status": "success", "message": msg or "", "value": agent_id or value or ""},
                        status_code=200)


def all_agents_sp(json_file: dict):
    try:
        return JSONResponse(content=_read_json("sp_agents_all", json_file), status_code=200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)


def one_agents_sp(json_file: dict):
    try:
        return JSONResponse(content=_read_json("sp_agents_one", json_file), status_code=200)
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)
